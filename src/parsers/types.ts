import type { ParsedItem } from '../db/index.js'

/** Результат одного запуска парсера */
export interface ParseOutput {
  /** Краткая сводка запуска — видна на дашборде и в /stats */
  summary: string
  /**
   * Собранные записи. Сохраняются в БД пачкой в одной транзакции,
   * с дедупликацией: неизменившиеся пропускаются, изменившиеся обновляются.
   */
  items?: ParsedItem[]
}

export interface ParserSource {
  /** Уникальное имя источника — попадает в БД и статистику */
  name: string
  /** Интервал между запусками, мс */
  intervalMs: number
  /**
   * Один цикл парсинга. Верни сводку и (опционально) записи;
   * при ошибке — бросай исключение.
   */
  run(): Promise<ParseOutput>
}
